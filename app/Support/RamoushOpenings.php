    /**
     * @param  array<int, array{k: string, v: string}>  $chips
     * @param  array<int, string>  $tasks
     * @param  array<int, string>  $must
     * @param  array<int, string>  $prefer
     * @param  array<int, string>  $growth
     * @param  array<int, string>  $kpis
     * @param  array<int, string>  $process
     * @param  array<int, string>  $impact
     * @param  array{portfolio: bool, quran: bool, branches: bool}  $formExtras
     * @param  array<int, array{name: string, seats: int}>  $branchRows
     * @return array<string, mixed>
     */
    private static function opening(
        string $title,
        string $category,
        array $chips,
        string $about,
        array $tasks,
        array $must,
        array $prefer,
        array $growth,
        array $kpis,
        array $process,
        string $gateRole,
        array $impact,
        array $formExtras,
        ?Carbon $expiresAt = null,
        array $branchRows = [],
        ?string $branchNote = null,
        ?string $lead = null,
    ): array {
        $blocks = [
            'about' => ['on' => true, 'title' => 'عن الدور', 'text' => $lead === null ? $about : $about.' '.$lead],
            'tasks' => ['on' => true, 'title' => 'أبرز المهام', 'items' => $tasks],
            'who' => ['on' => true, 'title' => 'المتطلبات والمؤهلات', 'must' => $must, 'prefer' => $prefer],
        ];

        if ($branchRows !== []) {
            $blocks['branches'] = [
                'on' => true,
                'title' => 'الفروع والشواغر المتوقعة عند الهدف',
                'rows' => $branchRows,
                'seat_label' => 'شاغر',
                'note' => $branchNote,
            ];
        }

        $blocks['growth'] = ['on' => true, 'title' => 'فرص النمو وما نقدمه', 'items' => $growth];
        $blocks['kpis'] = ['on' => true, 'title' => 'كيف نقيس النجاح؟', 'items' => $kpis];
        $blocks['process'] = [
            'on' => true,
            'title' => 'مراحل الاختيار',
            'items' => collect($process)->map(fn (string $step): array => ['k' => $step, 'v' => ''])->all(),
        ];

        $e = fn (string $text): string => htmlspecialchars($text, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');

        $description = '<h2>بوابة العبور القيمية — غير قابلة للتفاوض</h2>'
            .'<p>'.$e(self::GATE).'</p>'
            .'<p>'.$e($gateRole).'</p>'
            .'<h2>تعظيم الأثر والاصطفاف القيمي</h2>'
            .collect($impact)->map(fn (string $paragraph): string => '<p>'.$e($paragraph).'</p>')->implode('');

        return [
            'title' => $title,
            'category' => $category,
            'location' => null,
            'summary' => self::SUMMARY,
            'chips' => $chips,
            'blocks' => $blocks,
            'description' => $description,
            'form_lead' => $lead,
            'expires_at' => $expiresAt,
            'form_sections' => self::formSections(...$formExtras),
        ];
    }

    /**
     * Form fields follow each announcement's own application form (steps 2 and 3; step 1 is the built-in
     * name/phone/email). No nationality, age, gender or Quran-memorisation field or gate is added.
     *
     * @return array<int, array<string, mixed>>
     */
    private static function formSections(bool $portfolio, bool $quran, bool $branches): array
    {
        $field = fn (string $key, string $label, string $type, bool $required, array $extra = []): array => [
            'key' => $key, 'label' => $label, 'type' => $type, 'required' => $required, 'options' => [], ...$extra,
        ];

        $step2 = [
            $field('qualification', 'المؤهل العلمي والتخصص', 'text', true, ['max_length' => 255]),
            $field('years_experience', 'سنوات الخبرة', 'number', true),
            $field('relevant_experience', 'أبرز خبرة ذات صلة بالوظيفة', 'textarea', true, ['max_length' => 2000]),
            $field('works_at_school', 'هل تعمل/ين حاليًا في مدرسة القارئ العبقري؟', 'radio', false, [
                'options' => [['label' => 'نعم', 'value' => 'نعم'], ['label' => 'لا', 'value' => 'لا']],
            ]),
        ];

        if ($branches) {
            $step2[] = $field('preferred_branches', 'الفرع المفضل (يمكن اختيار فرعين)', 'checkbox_list', true, [
                'max_choices' => self::MAX_PREFERRED_BRANCHES,
                'options' => collect(array_keys(self::BRANCH_SEATS))->map(fn (string $name): array => ['label' => $name, 'value' => $name])->all(),
            ]);
        }

        $step3 = [
            $field('cv', 'السيرة الذاتية', 'file', true, ['max_file_size_kb' => 5120, 'accepted_file_types' => ['pdf', 'doc', 'docx']]),
            $field('qualification_images', 'صور المؤهلات العلمية', 'file', false, ['max_file_size_kb' => 5120, 'accepted_file_types' => ['pdf', 'jpg', 'jpeg', 'png'], 'multiple' => true]),
        ];

        if ($quran) {
            $step3[] = $field('quran_certificate', 'شهادة أو إجازة في القرآن الكريم (إن وجدت)', 'file', false, ['max_file_size_kb' => 5120, 'accepted_file_types' => ['pdf', 'jpg', 'jpeg', 'png']]);
        }

        if ($portfolio) {
            $step3[] = $field('portfolio_url', 'رابط ملف الأعمال', 'text', true, [
                'max_length' => 500,
                'pattern' => '^https?://\S+$',
                'pattern_message' => 'أدخل رابطًا صحيحًا يبدأ بـ https://',
            ]);
        }

        $step3[] = $field('acknowledge_truth', 'إقرار بصحة البيانات وبالالتزام بخماسية السكينة', 'checkbox', true);

        return [
            ['title' => 'المؤهل والخبرة', 'description' => null, 'fields' => $step2],
            ['title' => 'المرفقات والإقرار', 'description' => null, 'fields' => $step3],
        ];
    }
