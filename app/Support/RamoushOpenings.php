    /**
     * Creates the missing openings as drafts and returns how many were created.
     */
    public static function install(): int
    {
        $company = Company::query()->where('slug', 'g-reader-school')->first()
            ?? throw new RuntimeException('Company "g-reader-school" was not found; aborting without creating anything.');

        return DB::transaction(function () use ($company): int {
            $organization = CareerOrganization::query()->firstOrCreate(
                ['slug' => $company->slug],
                ['name' => $company->name, 'logo_path' => $company->logo_path, 'description' => $company->description],
            );

            $created = 0;

            foreach (self::openings() as $slug => $attributes) {
                $opening = CareerOpening::query()->firstOrCreate(['slug' => $slug], [
                    ...$attributes,
                    'company_id' => $company->id,
                    'career_organization_id' => $organization->id,
                    'status' => ListingStatus::Draft,
                    'published_at' => null,
                    'eligibility_rules' => [],
                    'identity_in_first_step' => false,
                ]);

                $created += $opening->wasRecentlyCreated ? 1 : 0;
            }

            return $created;
        });
    }

